"""Export the whole database as a frozen, auditable vintage.

WHY. The project freezes on a fixed date and the Neon free tier suspends idle projects. A frozen
project whose only copy of the data lives in a suspended database has not been frozen, it has been
lost. This script is the export step.

WHAT IT WRITES, into a dated folder:

    <table>.csv             one file per BASE TABLE, COPY ... CSV, so a person can read it
    schema-record.txt       columns, types, keys, indexes, constraints, extensions, view definitions
    naijadrugwatch.dump     pg_dump custom format, for an exact restore
    MANIFEST.json           row counts, column counts, sha256 and bytes per file, plus how it was made

WHAT IT DELIBERATELY DOES NOT WRITE. Rows of views or materialised views. They are derived from the
base tables and a second copy of a derived number is how a vintage drifts. Their DEFINITIONS are
recorded, so they can be rebuilt and refreshed from the exported tables.

The connection is opened read-only, twice: once in the session default, and once in the transaction.
The export cannot write to the source even if a line below is wrong.
"""

from __future__ import annotations

import hashlib
import json
import os
import shutil
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import envfile  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for block in iter(lambda: fh.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def main(argv: list[str]) -> int:
    label = argv[1] if len(argv) > 1 else datetime.now(timezone.utc).strftime("%Y-%m-%d")
    out = ROOT / "vintage" / label
    out.mkdir(parents=True, exist_ok=True)

    dsn = envfile.ensure_database_url()
    if not dsn:
        print("no DATABASE_URL: set it or put it in .env", file=sys.stderr)
        return 1

    import psycopg

    files: list[dict] = []
    with psycopg.connect(dsn, options="-c default_transaction_read_only=on") as conn:
        conn.read_only = True
        cur = conn.cursor()

        version, dbname, user = cur.execute(
            "select current_setting('server_version'), current_database(), current_user"
        ).fetchone()

        cur.execute(
            """
            select table_name from information_schema.tables
             where table_schema = 'public' and table_type = 'BASE TABLE'
             order by table_name
            """
        )
        tables = [r[0] for r in cur.fetchall()]
        print(f"server {version} db {dbname}; {len(tables)} base tables")

        for table in tables:
            rows = cur.execute(f'select count(*) from public."{table}"').fetchone()[0]
            cols = cur.execute(
                """
                select count(*) from information_schema.columns
                 where table_schema='public' and table_name=%s
                """,
                (table,),
            ).fetchone()[0]
            path = out / f"{table}.csv"
            copy_sql = (
                f'COPY (select * from public."{table}") TO STDOUT '
                f"WITH (FORMAT csv, HEADER true, ENCODING 'UTF8')"
            )
            with path.open("wb") as fh:
                with cur.copy(copy_sql) as cp:
                    for chunk in cp:
                        fh.write(chunk)
            data_lines = sum(1 for _ in path.open("rb")) - 1  # minus the header
            files.append(
                {
                    "file": path.name,
                    "table": table,
                    "db_rows": rows,
                    "csv_data_rows": data_lines,
                    "columns": cols,
                    "bytes": path.stat().st_size,
                    "sha256": sha256(path),
                    "rows_match": rows == data_lines,
                }
            )
            flag = "ok" if rows == data_lines else "MISMATCH"
            print(f"  {table:<32} {rows:>7} rows  {path.stat().st_size:>9} B  {flag}")

        schema_lines: list[str] = [
            f"-- schema record for vintage {label}",
            f"-- server_version {version}, database {dbname}, exported_by {user}",
            "-- generated by scripts/export_vintage.py; read-only session",
            "",
            "== extensions ==",
        ]
        for ext, ver in cur.execute(
            "select extname, extversion from pg_extension order by 1"
        ).fetchall():
            schema_lines.append(f"{ext} {ver}")

        schema_lines += ["", "== tables, columns =="]
        for table, col, typ, null, default in cur.execute(
            """
            select table_name, column_name, data_type, is_nullable, column_default
              from information_schema.columns
             where table_schema='public' and table_name = any(%s)
             order by table_name, ordinal_position
            """,
            (tables,),
        ).fetchall():
            schema_lines.append(
                f"{table}.{col} {typ} {'NULL' if null == 'YES' else 'NOT NULL'}"
                f"{' default ' + default if default else ''}"
            )

        schema_lines += ["", "== keys and constraints =="]
        for row in cur.execute(
            """
            select tc.table_name, tc.constraint_type, tc.constraint_name, kcu.column_name
              from information_schema.table_constraints tc
              left join information_schema.key_column_usage kcu
                on kcu.constraint_name = tc.constraint_name
               and kcu.table_schema = tc.table_schema
             where tc.table_schema='public'
             order by tc.table_name, tc.constraint_type, tc.constraint_name, kcu.ordinal_position
            """
        ).fetchall():
            schema_lines.append(" | ".join("" if v is None else str(v) for v in row))

        schema_lines += ["", "== indexes =="]
        for row in cur.execute(
            "select tablename, indexname, indexdef from pg_indexes "
            "where schemaname='public' order by tablename, indexname"
        ).fetchall():
            schema_lines.append(f"{row[0]} | {row[1]} | {row[2]}")

        schema_lines += ["", "== views and materialised views, definitions =="]
        for name, kind, definition in cur.execute(
            """
            select c.relname,
                   case when c.relkind = 'm' then 'MATERIALIZED VIEW' else 'VIEW' end,
                   pg_get_viewdef(c.oid, true)
              from pg_class c join pg_namespace n on n.oid = c.relnamespace
             where n.nspname = 'public' and c.relkind in ('v', 'm')
             order by c.relname
            """
        ).fetchall():
            schema_lines += ["", f"-- {kind} {name}", definition.strip(), ";"]

        schema_lines += ["", "== row-level freshness =="]
        for table, col in [("pharmacy_listings", "scraped_at"), ("price_history", "recorded_at"),
                           ("nafdac_status_snapshots", "observed_at"), ("scrape_runs", "started_at")]:
            try:
                lo, hi = cur.execute(
                    f'select min("{col}")::text, max("{col}")::text from public."{table}"'
                ).fetchone()
                schema_lines.append(f"{table}.{col} {lo} .. {hi}")
            except Exception as exc:  # column name differs; record that rather than guess
                conn.rollback()
                schema_lines.append(f"{table}.{col} not read: {exc.__class__.__name__}")

    schema_path = out / "schema-record.txt"
    schema_path.write_text("\n".join(schema_lines) + "\n", encoding="utf-8")
    files.append(
        {
            "file": schema_path.name,
            "table": "(schema)",
            "bytes": schema_path.stat().st_size,
            "sha256": sha256(schema_path),
        }
    )

    dump_name = "naijadrugwatch.dump"
    pg_dump = shutil.which("pg_dump") or shutil.which("pg_dump.cmd")
    dump_state = "not attempted"
    if pg_dump:
        proc = subprocess.run(
            [pg_dump, f"--dbname={dsn}", "--format=custom", "--no-owner",
             "--no-privileges", f"--file={out / dump_name}"],
            capture_output=True, text=True,
        )
        if proc.returncode == 0:
            dump_state = "ok"
            files.append(
                {
                    "file": dump_name,
                    "table": "(all, pg_dump custom)",
                    "bytes": (out / dump_name).stat().st_size,
                    "sha256": sha256(out / dump_name),
                }
            )
        else:
            dump_state = f"FAILED rc={proc.returncode}: {proc.stderr.strip()[:400]}"
    print(f"pg_dump: {dump_state}")

    try:
        head = subprocess.run(
            ["git", "rev-parse", "HEAD"], cwd=ROOT, capture_output=True, text=True
        ).stdout.strip()
        dirty = subprocess.run(
            ["git", "status", "--porcelain"], cwd=ROOT, capture_output=True, text=True
        ).stdout.strip().splitlines()
    except OSError:
        head, dirty = "", []

    manifest = {
        "vintage": label,
        "exported_at_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "server_version": version,
        "database": dbname,
        "read_only_session": True,
        "repo_head": head,
        "uncommitted_paths": dirty,
        "python": sys.version.split()[0],
        "pg_dump": dump_state,
        "note": (
            "Base tables only. Views and materialised views are derived; their definitions are in "
            "schema-record.txt and must be rebuilt, not loaded from this folder."
        ),
        "files": files,
        "totals": {
            "files": len(files),
            "bytes": sum(f.get("bytes", 0) for f in files),
            "base_rows": sum(f.get("db_rows", 0) for f in files),
            "row_count_mismatches": [f["table"] for f in files if f.get("rows_match") is False],
        },
    }
    (out / "MANIFEST.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")

    print(f"\nwrote {out}")
    print(f"  total {manifest['totals']['bytes']} B over {manifest['totals']['files']} files")
    print(f"  base rows {manifest['totals']['base_rows']}")
    print(f"  row-count mismatches: {manifest['totals']['row_count_mismatches'] or 'none'}")
    return 0 if not manifest["totals"]["row_count_mismatches"] else 2


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
